#!/usr/bin/env python3
"""The prompt echo's completeness, over the serve protocol.

`POST /v1/completions` with `echo: true` + `logprobs` promises a logprob and a
text offset for EVERY prompt position, and that is what a scoring harness reads:
it slices the continuation's tokens out of that run. The gateway enforces the
same contract on the wire -- a run that starts anywhere but position 0 is
refused by name (`engine_pinned_prefix_not_echoed`), never served with every
logprob shifted by one token.

qwen36.c's read-out emitted the block's positions 1..S-1, and position 0 only
when a pin photo carried its logits. A fresh slot has no photo, so any client
that does not send `pin=1` -- which is every OpenAI-compatible scorer -- got a
run starting at 1. The same read-out could also resume a live prefix while the
channel was on, which leaves the reused positions without frames. Both halves
are pinned here:

  * a cold request: ECHO frames from 0, contiguous, position 0 carrying " nan 0"
    (nothing conditions it);
  * a request whose prompt EXTENDS the previous one: the same, from 0 -- a live
    prefix is not resumed while the read-out is on, so the run still starts
    where the caller reads from;
  * a request that does not ask for the channel: no ECHO frame at all (the
    opt-in stays opt-in, and a plain turn pays nothing).

Recipe (CPU is enough; the fixture is generated, not committed):

    make -C c qwen36 qwen36-tiny-v128-generate
    python3 c/tests/qwen36_echo_serve_harness.py c/qwen36_tiny_v128_c

Exit status is the gate: 0 when every check passes, 1 otherwise.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from prefix_serve_harness import ServeEngine, ensure_byte_tokenizer   # noqa: E402


class EchoEngine(ServeEngine):
    """A serve engine that keeps the ECHO frames of the request it just ran."""

    def ask_echo(self, rid, prompt, max_tok=1, topk=5):
        """(echo frames, generated bytes). `topk=None` sends no extension at all."""
        assert isinstance(prompt, bytes), "prompts stay bytes end to end"
        ext = f" logprobs={topk}" if topk else ""
        # qwen36 reads a 6-field SUBMIT header: the keys follow top_p directly, with
        # no gbytes field in between (that field is colibri.c's and mimo.c's shape).
        header = f"SUBMIT {rid} 0 {len(prompt)} {max_tok} 0 1{ext}\n".encode()
        self.p.stdin.write(header + prompt + b"\n")
        self.p.stdin.flush()
        echoes, chunks = [], []
        while True:
            line = self.p.stdout.readline()
            if not line:
                raise RuntimeError("engine closed mid-request:\n"
                                   + "".join(self._err)[-2000:])
            text = line.decode("latin-1").rstrip("\n")
            parts = text.split(" ")
            kind = parts[0]
            if kind == "ECHO":                       # ECHO <id> <n> <pos> <tail...>
                n = int(parts[2])
                tail = " ".join(parts[4:])
                if n:
                    self.p.stdout.read(n)
                    self.p.stdout.readline()         # the newline after the payload
                echoes.append((int(parts[3]), tail))
            elif kind == "DATA":
                chunks.append(self.p.stdout.read(int(parts[2])))
                self.p.stdout.readline()
            elif kind in ("DONE", "END"):
                return echoes, b"".join(chunks)
            elif kind == "ERROR":
                raise RuntimeError(f"engine error: {text}")


def run_checks(engine, problems):
    def check(name, echoes, expected):
        if not expected:
            if echoes:
                problems.append(f"{name}: {len(echoes)} ECHO frame(s) for a request "
                                "that did not ask for the channel")
            return
        if not echoes:
            problems.append(f"{name}: no ECHO frame at all")
            return
        positions = [pos for pos, _tail in echoes]
        if positions != list(range(len(positions))):
            # The whole point of the frame run: a caller reads it position by position,
            # so a gap or a start past 0 is silently wrong data, not a slow answer.
            problems.append(f"{name}: echo positions {positions} are not a contiguous "
                            "run from 0")
        if echoes[0][1].strip() != "nan 0":
            problems.append(f"{name}: position 0 carries {echoes[0][1]!r}, "
                            "expected ' nan 0'")

    cold, _ = engine.ask_echo(1, b"Hello")
    check("cold request", cold, expected=True)

    # The same prompt again, and then one that EXTENDS it: the second one finds the
    # first's state as a strict prefix, which is exactly the live-prefix resume the
    # channel must refuse while it is on.
    warm, _ = engine.ask_echo(2, b"Hello")
    check("repeated prompt", warm, expected=True)
    extended, _ = engine.ask_echo(3, b"Hello there")
    check("extended prompt", extended, expected=True)

    plain, _ = engine.ask_echo(4, b"Hello there", topk=None)
    check("no channel requested", plain, expected=False)


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    fixture = Path(sys.argv[1])
    engine_path = Path(__file__).resolve().parent.parent / "qwen36"
    if not engine_path.exists():
        print(f"FAIL: {engine_path} is not built (make -C c qwen36)")
        return 1
    if not (fixture / "config.json").exists():
        print(f"FAIL: {fixture} is not a container "
              "(make -C c qwen36-tiny-v128-generate)")
        return 1
    ensure_byte_tokenizer(fixture, size=128)
    engine = EchoEngine(engine_path, [],
                        {"SNAP": str(fixture), "SERVE": "1", "SERVE_BATCH": "1",
                         "KV_SLOTS": "1"})
    problems = []
    try:
        run_checks(engine, problems)
    finally:
        stderr = engine.close()
    if problems:
        for problem in problems:
            print(f"FAIL: {problem}")
        if stderr:
            print("--- engine stderr ---")
            print(stderr[-2000:])
        return 1
    print("PASS: the echo run starts at 0, is contiguous, and position 0 is ' nan 0'; "
          "an extending prompt no longer resumes a live prefix while the channel is on")
    return 0


if __name__ == "__main__":
    sys.exit(main())
