#!/usr/bin/env python3
"""Token-exact checks for the Kimi K3 engine against an independent oracle.

Dependency-free (stdlib only).  The fixture is generated by
tools/make_kimi_k3_tiny.py (numpy, deterministic); the expected tokens in
ref.json come from Moonshot's own modeling code via tools/make_kimi_k3_ref.py
(run offline by a maintainer, vendor files pinned by SHA-256), so the engine
and its oracle never share an author.

What is checked, all token-exact (argmax, no tolerances):
  - greedy generation for three cases (short; 40 tokens crossing the default
    32-token prefill chunk; 72 tokens crossing it twice)
  - teacher forcing at every position via the K3_LOGITS dump
  - determinism (two identical runs, identical tokens)
  - the oracle BITES: one corrupted expert scale byte per layer-2 expert must
    change the output (guards against a test that silently compares nothing)

The engine runs in its exact-math configuration (ref.json's engine_env:
K3_BITS/K3_MLA_BITS/K3_HEAD_BITS=32 because the fixture stores f32 dense
weights, K3_IDOT=0 because int8-activation expert matmuls are a documented
~0.4%/group speed approximation, not an oracle target).  The fixture ships
no tokenizer.json on purpose: the engine then prints raw token ids on
stdout, which is what this test parses.
"""

import argparse
import array
import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path


def run_engine(binary, fixture, prompt_ids, max_new, env, extra_env=None):
    run_env = dict(os.environ, **env)
    if extra_env:
        run_env.update(extra_env)
    result = subprocess.run(
        [binary, str(fixture), "--ids", " ".join(map(str, prompt_ids)),
         "--ngen", str(max_new)],
        env=run_env, capture_output=True, text=True, timeout=600)
    if result.returncode != 0:
        raise AssertionError(
            f"engine exited {result.returncode}:\n{result.stderr[-2000:]}")
    # without a tokenizer.json the engine prints "id id id ... TUNE decode:"
    return [int(token) for token in result.stdout.split("TUNE")[0].split()]


def check_greedy(binary, fixture, reference):
    for name, case in reference["cases"].items():
        got = run_engine(binary, fixture, case["prompt_ids"],
                         case["max_new_tokens"], reference["engine_env"])
        want = case["greedy_new_ids"]
        if got != want:
            raise AssertionError(
                f"greedy mismatch in case '{name}': engine {got} vs "
                f"reference {want}")
        print(f"ok greedy {name}: {len(want)}/{len(want)} tokens")


def check_determinism(binary, fixture, reference):
    case = reference["cases"]["short"]
    first = run_engine(binary, fixture, case["prompt_ids"],
                       case["max_new_tokens"], reference["engine_env"])
    second = run_engine(binary, fixture, case["prompt_ids"],
                        case["max_new_tokens"], reference["engine_env"])
    if first != second:
        raise AssertionError(f"non-deterministic greedy: {first} vs {second}")
    print("ok determinism: two identical runs, identical tokens")


def check_teacher_forcing(binary, fixture, reference, vocab):
    for name, case in reference["cases"].items():
        full = case["greedy_full_ids"]
        with tempfile.NamedTemporaryFile(suffix=".f32", delete=False) as tmp:
            logits_path = tmp.name
        try:
            run_engine(binary, fixture, full, 0, reference["engine_env"],
                       extra_env={"K3_LOGITS": logits_path})
            raw = array.array("f")
            with open(logits_path, "rb") as fh:
                raw.frombytes(fh.read())
        finally:
            os.unlink(logits_path)
        if len(raw) != len(full) * vocab:
            raise AssertionError(
                f"case '{name}': K3_LOGITS dumped {len(raw)} floats, "
                f"expected {len(full) * vocab}")
        got = []
        for position in range(len(full)):
            row = raw[position * vocab:(position + 1) * vocab]
            got.append(max(range(vocab), key=row.__getitem__))
        want = case["teacher_forcing_ids"]
        if got != want:
            first_bad = next(i for i, (a, b) in enumerate(zip(got, want))
                             if a != b)
            raise AssertionError(
                f"teacher forcing mismatch in case '{name}' at position "
                f"{first_bad}: engine {got[first_bad]} vs reference "
                f"{want[first_bad]}")
        print(f"ok teacher forcing {name}: {len(want)}/{len(want)} positions")


def check_oracle_bites(binary, fixture, reference, experts):
    """One corrupted scale byte per layer-2 expert must change the output.
    Without this, a comparator bug that accepts anything would pass silently."""
    corrupt = Path(tempfile.mkdtemp(prefix="kimi-k3-tiny-bite-")) / "fixture"
    shutil.copytree(fixture, corrupt)
    try:
        model = corrupt / "model.safetensors"
        raw = bytearray(model.read_bytes())
        header_len = struct.unpack("<Q", bytes(raw[:8]))[0]
        header = json.loads(bytes(raw[8:8 + header_len]))
        for expert in range(experts):
            name = (f"model.layers.2.block_sparse_moe.experts.{expert}"
                    f".w1.weight_scale")
            lo, _ = header[name]["data_offsets"]
            offset = 8 + header_len + lo
            raw[offset] = (raw[offset] + 3) % 256   # 2^3 on one group
        model.write_bytes(bytes(raw))
        diverged = 0
        for case in reference["cases"].values():
            got = run_engine(binary, corrupt, case["prompt_ids"],
                             case["max_new_tokens"], reference["engine_env"])
            if got != case["greedy_new_ids"]:
                diverged += 1
        if not diverged:
            raise AssertionError(
                "corrupted expert scales produced identical tokens in every "
                "case: the oracle does not bite")
        print(f"ok oracle bites: corrupted expert scales diverge in "
              f"{diverged}/{len(reference['cases'])} cases")
    finally:
        shutil.rmtree(corrupt.parent)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--binary", required=True)
    parser.add_argument("--fixture", required=True)
    args = parser.parse_args()

    fixture = Path(args.fixture)
    reference = json.loads((fixture / "ref.json").read_text())
    if reference.get("source") != "moonshot-vendor":
        raise AssertionError(
            "ref.json must come from the independent vendor implementation "
            f"(source={reference.get('source')!r})")
    config = json.loads((fixture / "config.json").read_text())
    if (fixture / "tokenizer.json").exists():
        raise AssertionError(
            "fixture must not ship tokenizer.json: raw-id stdout is the "
            "comparison channel")

    check_greedy(args.binary, fixture, reference)
    check_determinism(args.binary, fixture, reference)
    check_teacher_forcing(args.binary, fixture, reference,
                          config["vocab_size"])
    check_oracle_bites(args.binary, fixture, reference,
                       config["num_experts"])
    print("kimi-k3-tiny-check: all checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
