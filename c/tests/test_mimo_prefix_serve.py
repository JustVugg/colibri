"""KV prefix reuse and Brio photos on MiMo-V2.6, against the tiny fixture.

MiMo is the engine where a photo is more than token ids. Most of its layers
attend a sliding window, and a windowed layer keeps its keys in a RING: position
p in slot p % window. The photo of a prompt of P tokens holds the ring as it was
at P; the first option then writes its own positions into the slots of P - window
and onwards, so after one option the ring no longer describes the photo. A photo
that kept only the ids -- enough for the full-attention layers, whose rows below
P nobody touches -- would hand the second option a ring from the first. The
fixture's window is 8 tokens, and every prompt below outgrows it.

What is checked, all against a cold engine and to the last printed digit of
every ECHO frame (the log-probability of the token and the whole top-k):

  - the shared prefix-reuse contract (tests/prefix_serve_harness.py);
  - options that cross the window resume from the photo exactly, one after the
    other, with an ordinary chat turn in between that must not take the photo
    away, and each one PROCESSES ONLY ITS OWN TOKENS: its read-out starts at the
    photo's end and the engine says it prefilled the option and nothing more.
    The numbers alone would not show a photo that silently fell back to a full
    recompute; the positions and the count do;
  - nested photos (a state, then a question) and a sibling question that
    overwrites the deeper one's rows: the engine falls back to the shallower;
  - a photo whose rows an unrelated prompt overwrote is released, not restored;
  - pictures: a prompt with an image never resumes from a photo, and a prompt
    with an image takes none, because token ids do not describe the picture;
  - the read-out covers every position from 0 unless a photo covers the prefix,
    which is what the gateway's `echo` needs, and never resumes from a live
    prefix;
  - asking for logprobs changes no generated byte;
  - a read-only request may fill the context, a generating one may not.

Needs the built engine and the fixture: `make mimo mimo-tiny-generate`.
"""
import json
import math
import re
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import mimo_serve_fixture as fixture  # noqa: E402
from prefix_serve_harness import PrefixReuseContract, ServeEngine  # noqa: E402

STATE = "Context: the release is late, the tests are red and the changelog is empty.\n"
QUESTION = STATE + "Question: should we ship it today?\nAnswer:"
SIBLING = STATE + "Question: who has to sign it off?\nAnswer:"
OPTIONS = (" only after the tests pass and the changelog says what changed",
           " yes",
           " no, not today",
           " only after the tests pass and the changelog says what changed")


def window():
    config = json.loads((fixture.FIXTURE / "config.json").read_text())
    return int(config["sliding_window"])


class Client(ServeEngine):
    """A serve engine read frame by frame: the ECHO frames are what is compared."""

    def __init__(self, log_prefix=True, **env):
        super().__init__(fixture.ENGINE, ["8"], fixture.engine_env(**env),
                         log_prefix=log_prefix)

    def image(self, rid):
        payload, grid_h, grid_w, _pads = fixture.image_payload()
        self.p.stdin.write(f"IMAGE {rid} {len(payload)} {grid_h} {grid_w}\n".encode()
                           + payload + b"\n")
        self.p.stdin.flush()

    def submit(self, rid, prompt, max_tokens=0, ext=" logprobs=3"):
        """Returns {kind: ..., "echo": {pos: tail}, "data": [(bytes, tail)], "end": line}.

        A tail is the frame's numeric part after the position, compared as text:
        the log-probability and every top-k candidate, as the engine printed them."""
        data = prompt.encode()
        self.p.stdin.write(f"SUBMIT {rid} 0 {len(data)} {max_tokens} 0 1{ext}\n".encode()
                           + data + b"\n")
        self.p.stdin.flush()
        out = {"echo": {}, "data": [], "accept": None, "end": None}
        while True:
            line = self.p.stdout.readline()
            if not line:
                raise RuntimeError("engine closed mid-request:\n" + "".join(self._err)[-2000:])
            fields = line.decode("latin-1").split()
            if not fields:
                continue
            if fields[0] in ("ECHO", "DATA"):
                payload = self.p.stdout.read(int(fields[2]))
                self.p.stdout.read(1)
                if fields[0] == "ECHO":
                    pos = int(fields[3])
                    if pos in out["echo"]:
                        raise AssertionError(f"position {pos} read out twice")
                    out["echo"][pos] = " ".join(fields[4:])
                else:
                    out["data"].append((payload, " ".join(fields[3:])))
            elif fields[0] == "ACCEPT":
                out["accept"] = int(fields[2])
            elif fields[0] in ("DONE", "ERROR"):
                out["end"] = fields
                return out


def resumed(log):
    """[(photo length, tokens prefilled)] in order, from the engine's own account."""
    return [(int(a), int(b)) for a, b in
            re.findall(r"\[PIN\] resumed from the photo of (\d+) tokens, (\d+) to prefill", log)]


