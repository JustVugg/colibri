#!/usr/bin/env python3
"""Recurrent-state checkpoints (COLI_K3_CKPT) against the tiny K3 fixture.

The scenario is the agentic edit kv-prefix reuse cannot serve: turn 2 shares
only the OPENING of turn 1's prompt and diverges after it (an edited question,
a replaced tool result). Today that is a full reset plus a full re-prefill,
because the 69 KDA layers carry a recurrent state that cannot be rewound.
With checkpoints enabled the engine restores the photo taken at turn 1's
prompt boundary and recomputes only the tail.

What is asserted, all deterministic:
  - OPT-IN INVARIANT: with COLI_K3_CKPT unset the engine emits no [K3-CKPT]
    line and behaves as before (this is the default-off run itself).
  - IDENTITY: every request's DATA bytes are identical with checkpoints off
    and on. The feature may only change WORK, never tokens.
  - RESTORE DEPTH: with checkpoints on, the divergent turns restore at
    exactly turn 1's ACCEPT np (the prompt-boundary photo), and the engine
    recomputes prompt_len - np tokens instead of prompt_len.

The serve protocol needs a tokenizer, and the base fixture ships none on
purpose (the oracle test parses raw-id stdout). So this test builds a derived
fixture in a tempdir: config + weights from the base fixture plus
tests/tok_kimi_tiny.json as tokenizer.json. The fixture's vocab (320) covers
every id that tokenizer can emit (<= 285).
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


class Serve:
    """One persistent SERVE=1 kimi_k3 process; stderr goes to a file so the
    pipe can never fill and deadlock the engine."""

    def __init__(self, binary, model, extra_env, stderr_path):
        env = dict(os.environ, SERVE="1", SNAP=str(model), K3_PREFIX_LOG="1")
        env.update(extra_env)
        self.stderr_file = open(stderr_path, "wb")
        self.process = subprocess.Popen(
            [str(binary)], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=self.stderr_file, env=env)
        self.counter = 0

    def submit(self, prompt, max_tokens):
        """Returns (generated bytes, ACCEPT np) for one request."""
        self.counter += 1
        request_id = f"r{self.counter}"
        payload = prompt.encode("utf-8")
        header = (f"SUBMIT {request_id} 0 {len(payload)} {max_tokens} "
                  f"0.0 1.0\n").encode("ascii")
        self.process.stdin.write(header + payload + b"\n")
        self.process.stdin.flush()
        pieces, accept_np = [], -1
        stream = self.process.stdout
        while True:
            line = stream.readline()
            if not line:
                raise AssertionError(
                    f"engine closed stdout during {request_id}")
            fields = line.decode("utf-8", "replace").split()
            if not fields:
                continue
            if fields[0] == "ERROR":
                raise AssertionError(f"engine ERROR: {line!r}")
            if fields[0] == "ACCEPT" and len(fields) >= 3:
                accept_np = int(fields[2])
            elif fields[0] == "DATA" and len(fields) == 3:
                size = int(fields[2])
                pieces.append(stream.read(size))
                stream.read(1)                    # trailing newline
            elif fields[0] == "DONE":
                break
            # READY / PROF and other frames are irrelevant here
        return b"".join(pieces), accept_np

    def close(self):
        try:
            if self.process.stdin:
                self.process.stdin.close()
            self.process.wait(timeout=30)
        except Exception:
            self.process.kill()
        self.stderr_file.close()


PROMPT_BASE = "Alpha beta gamma delta epsilon zeta.\n"
TAIL_A = "Question about apples?\n"
TAIL_B = "Question about bridges?\n"
MAX_NEW = 6


def run_session(binary, model, extra_env, stderr_path):
    serve = Serve(binary, model, extra_env, stderr_path)
    try:
        results = [serve.submit(PROMPT_BASE, MAX_NEW),
                   serve.submit(PROMPT_BASE + TAIL_A, MAX_NEW),
                   serve.submit(PROMPT_BASE + TAIL_B, MAX_NEW)]
    finally:
        serve.close()
    return results, Path(stderr_path).read_text(errors="replace")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--binary", required=True)
    parser.add_argument("--fixture", required=True)
    parser.add_argument("--tokenizer",
                        default=str(Path(__file__).parent /
                                    "tok_kimi_tiny.json"))
    args = parser.parse_args()

    base = Path(args.fixture)
    work = Path(tempfile.mkdtemp(prefix="kimi-k3-ckpt-"))
    try:
        model = work / "fixture"
        model.mkdir()
        shutil.copy(base / "config.json", model / "config.json")
        shutil.copy(base / "model.safetensors", model / "model.safetensors")
        shutil.copy(args.tokenizer, model / "tokenizer.json")

        off, err_off = run_session(args.binary, model, {},
                                   work / "off.stderr")
        on, err_on = run_session(args.binary, model, {"COLI_K3_CKPT": "4"},
                                 work / "on.stderr")
        disk_dir = work / "photos"
        disk_dir.mkdir()
        disk, err_disk = run_session(
            args.binary, model,
            {"COLI_K3_CKPT": "4", "COLI_K3_CKPT_DIR": str(disk_dir)},
            work / "disk.stderr")

        # opt-in invariant: the default run must not know the feature exists
        if "[K3-CKPT]" in err_off:
            raise AssertionError(
                "COLI_K3_CKPT unset but the engine logged checkpoint "
                "activity: the feature is not opt-in")
        print("ok opt-in: default run has no checkpoint activity")

        # identity: the feature may change work, never tokens
        for index, (off_result, on_result) in enumerate(zip(off, on), 1):
            if off_result[0] != on_result[0]:
                raise AssertionError(
                    f"request {index}: output differs between checkpoint "
                    f"modes: {off_result[0]!r} vs {on_result[0]!r}")
            if off_result[1] != on_result[1]:
                raise AssertionError(
                    f"request {index}: prompt token count differs between "
                    f"modes ({off_result[1]} vs {on_result[1]})")
        print("ok identity: all 3 requests byte-identical across modes")

        # scenario validity: in the baseline the divergent turns really are
        # the case kv-prefix reuse cannot serve
        if err_off.count("[PREFIX] no reuse") < 2:
            raise AssertionError(
                "baseline did not hit the divergent-prompt path; the "
                "scenario no longer tests checkpoints:\n" + err_off)

        # restore depth: both divergent turns restore at exactly turn 1's
        # prompt boundary and recompute only their tail
        np1 = off[0][1]
        restores = [(int(pos), int(total), int(recompute))
                    for pos, total, recompute in re.findall(
                        r"\[K3-CKPT\] restored pos=(\d+) of (\d+) prompt "
                        r"tokens \(recompute (\d+)\)", err_on)]
        if len(restores) != 2:
            raise AssertionError(
                f"expected 2 checkpoint restores (turns 2 and 3), saw "
                f"{len(restores)}:\n{err_on}")
        for turn, (pos, total, recompute) in zip((2, 3), restores):
            expect_total = on[turn - 1][1]
            if pos != np1 or total != expect_total or \
                    recompute != expect_total - np1:
                raise AssertionError(
                    f"turn {turn}: restored pos={pos} of {total} "
                    f"(recompute {recompute}), expected pos={np1} of "
                    f"{expect_total} (recompute {expect_total - np1})")
            print(f"ok restore turn {turn}: {pos}/{total} reused, "
                  f"{recompute} recomputed instead of {total}")
        if "[K3-CKPT] saved" not in err_on:
            raise AssertionError("no checkpoint was ever saved:\n" + err_on)

        # disk mode: same photos parked in files. Identity and restore depth
        # must match the RAM mode exactly, and the blobs must be ON DISK.
        for index, (ram_result, disk_result) in enumerate(zip(on, disk), 1):
            if ram_result != disk_result:
                raise AssertionError(
                    f"request {index}: disk mode diverged from RAM mode: "
                    f"{disk_result!r} vs {ram_result!r}")
        disk_restores = re.findall(
            r"\[K3-CKPT\] restored pos=(\d+) of (\d+) prompt "
            r"tokens \(recompute (\d+)\)", err_disk)
        if [tuple(map(int, r)) for r in disk_restores] != restores:
            raise AssertionError(
                f"disk-mode restores {disk_restores} differ from RAM-mode "
                f"{restores}:\n{err_disk}")
        photos = sorted(f.name for f in disk_dir.glob("k3_ckpt_*.bin"))
        if not photos:
            raise AssertionError(
                "disk mode restored correctly but wrote no photo files: "
                "the blobs are not actually on disk")
        print(f"ok disk mode: identical outputs and restores, "
              f"{len(photos)} photo file(s) on disk")
        print("kimi-k3-ckpt: all checks passed")
        return 0
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
