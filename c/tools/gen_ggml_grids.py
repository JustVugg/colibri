#!/usr/bin/env python3
"""Generate c/ggml_grids.h: the lookup tables the GGUF i-quant formats decode with.

The tables are data, not code: the IQ codebooks (iq2xxs/iq2xs/iq2s/iq3xxs/
iq3s/iq1s grids), the 7-to-8 bit sign table and the IQ4_NL / MXFP4 value
tables. They are taken from gguf-py (the reference Python package of the GGUF
format, MIT licensed, copyright the ggml authors), where they already exist in
a packed form, and written out as plain byte arrays so the C decoders in
ggml_quants.h index them directly.

Run from c/:  python3 tools/gen_ggml_grids.py > ggml_grids.h
"""
import sys
import numpy as np
import gguf.quants as q


def grid_bytes(cls):
    cls.init_grid()
    g = np.asarray(cls.grid).reshape(cls.grid_shape)
    return g


def emit_u8(name, arr, per_line=16):
    flat = [int(v) & 0xFF for v in np.asarray(arr).reshape(-1)]
    out = [f"static const uint8_t {name}[{len(flat)}] = {{"]
    for i in range(0, len(flat), per_line):
        out.append("    " + ", ".join(f"0x{v:02x}" for v in flat[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def emit_i8(name, arr, per_line=16):
    flat = [int(v) for v in np.asarray(arr).reshape(-1)]
    out = [f"static const int8_t {name}[{len(flat)}] = {{"]
    for i in range(0, len(flat), per_line):
        out.append("    " + ", ".join(f"{v}" for v in flat[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    parts = ["""/* ggml_grids.h -- GENERATED by tools/gen_ggml_grids.py, do not edit.
 *
 * Lookup tables for the GGUF i-quant and fp4 formats (see ggml_quants.h).
 * Values from gguf-py, the reference Python implementation of GGUF
 * (MIT License, Copyright (c) 2023-2026 The ggml authors).
 *
 * Grid rows are stored one byte per weight: GGML_IQ2XXS_GRID[i*8 + j] is
 * element j of codebook entry i, exactly the byte the reference grids hold.
 */
#ifndef GGML_GRIDS_H
#define GGML_GRIDS_H
#include <stdint.h>
"""]
    for cname, cls, width in (("GGML_IQ2XXS_GRID", q.IQ2_XXS, 8),
                              ("GGML_IQ2XS_GRID", q.IQ2_XS, 8),
                              ("GGML_IQ2S_GRID", q.IQ2_S, 8),
                              ("GGML_IQ3XXS_GRID", q.IQ3_XXS, 4),
                              ("GGML_IQ3S_GRID", q.IQ3_S, 4)):
        g = grid_bytes(cls)
        assert g.shape[1] == width, (cname, g.shape)
        parts.append(f"/* {g.shape[0]} entries x {width} */")
        parts.append(emit_u8(cname, g.astype(np.int64)))
    g1 = grid_bytes(q.IQ1_S)
    assert g1.shape == (2048, 8)
    parts.append("/* 2048 entries x 8, values in {-1, 0, 1} */")
    parts.append(emit_i8("GGML_IQ1S_GRID", g1.astype(np.int64)))
    parts.append(emit_u8("GGML_KSIGNS_IQ2XS", np.frombuffer(q.IQ2_XXS.ksigns, dtype=np.uint8)))
    # sign byte -> eight int8 of +1 / -1 (bit j set = element j negative): a
    # constant, so no thread ever sees it half built
    sign8 = np.array([[(-1 if (v >> j) & 1 else 1) for j in range(8)] for v in range(256)], dtype=np.int8)
    parts.append("/* 256 sign bytes x 8, +1 / -1 */")
    parts.append(emit_i8("GGML_SIGN8", sign8))
    parts.append(emit_i8("GGML_KVALUES_IQ4NL", q.IQ4_NL.kvalues))
    parts.append(emit_i8("GGML_KVALUES_MXFP4", q.MXFP4.kvalues))
    parts.append("#endif")
    sys.stdout.write("\n\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
