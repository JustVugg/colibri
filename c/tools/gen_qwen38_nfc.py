#!/usr/bin/env python3
"""Generate the dependency-free Unicode NFC tables used by qwen38.c."""

from __future__ import annotations

import argparse
import unicodedata
from pathlib import Path


MAX_CODEPOINT = 0x110000


def canonical_decompositions() -> tuple[list[tuple[int, int, int]], list[int]]:
    rows: list[tuple[int, int, int]] = []
    values: list[int] = []
    for codepoint in range(MAX_CODEPOINT):
        raw = unicodedata.decomposition(chr(codepoint))
        if not raw or raw.startswith("<"):
            continue
        decomposition = [int(value, 16) for value in raw.split()]
        rows.append((codepoint, len(values), len(decomposition)))
        values.extend(decomposition)
    return rows, values


def combining_classes() -> list[tuple[int, int]]:
    return [
        (codepoint, value)
        for codepoint in range(MAX_CODEPOINT)
        if (value := unicodedata.combining(chr(codepoint)))
    ]


def compositions() -> list[tuple[int, int, int]]:
    rows: list[tuple[int, int, int]] = []
    for codepoint in range(MAX_CODEPOINT):
        raw = unicodedata.decomposition(chr(codepoint))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(value, 16) for value in raw.split()]
        if len(parts) != 2:
            continue
        pair = chr(parts[0]) + chr(parts[1])
        if unicodedata.normalize("NFC", pair) == chr(codepoint):
            rows.append((parts[0], parts[1], codepoint))
    rows.sort()
    return rows


def render() -> str:
    decompositions, decomposition_values = canonical_decompositions()
    classes = combining_classes()
    composition_rows = compositions()
    lines = [
        "/* GENERATED by tools/gen_qwen38_nfc.py -- do not edit by hand.",
        f" * Unicode Character Database {unicodedata.unidata_version}. */",
        "#ifndef COLI_QWEN38_NFC_TABLES_H",
        "#define COLI_QWEN38_NFC_TABLES_H",
        "#include <stdint.h>",
        "typedef struct { uint32_t cp, offset; uint8_t length; } Q38NfcDecomp;",
        "typedef struct { uint32_t cp; uint8_t ccc; } Q38NfcCcc;",
        "typedef struct { uint32_t first, second, composite; } Q38NfcCompose;",
        f"static const Q38NfcDecomp q38_nfc_decomp[{len(decompositions)}] = {{",
    ]
    lines.extend(
        f"    {{0x{cp:x}, {offset}, {length}}},"
        for cp, offset, length in decompositions
    )
    lines.append("};")
    lines.append(
        f"static const uint32_t q38_nfc_decomp_values[{len(decomposition_values)}] = {{"
    )
    for start in range(0, len(decomposition_values), 12):
        values = ", ".join(
            f"0x{value:x}" for value in decomposition_values[start : start + 12]
        )
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            f"static const Q38NfcCcc q38_nfc_ccc[{len(classes)}] = {{",
        ]
    )
    lines.extend(f"    {{0x{cp:x}, {ccc}}}," for cp, ccc in classes)
    lines.extend(
        [
            "};",
            f"static const Q38NfcCompose q38_nfc_compose[{len(composition_rows)}] = {{",
        ]
    )
    lines.extend(
        f"    {{0x{first:x}, 0x{second:x}, 0x{composite:x}}},"
        for first, second, composite in composition_rows
    )
    lines.extend(["};", "#endif /* COLI_QWEN38_NFC_TABLES_H */", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "qwen38_nfc_tables.h",
    )
    args = parser.parse_args()
    args.out.write_text(render(), encoding="utf-8")
    print(f"wrote {args.out} (Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
