"""Generate the Unicode data used by the nomic WordPiece normalizer.

The runtime is C-only and must not depend on ICU.  Python's Unicode database
is used at build-maintenance time to emit canonical (NFD) decompositions,
combining-mark ranges, and Unicode lowercase mappings.
"""

import unicodedata


def cps(text):
    return [ord(c) for c in text]


def canonical(cp):
    raw = unicodedata.decomposition(chr(cp))
    if not raw or raw.startswith("<"):
        return [cp]
    out = []
    for part in raw.split():
        out.extend(canonical(int(part, 16)))
    return out


def emit_ranges(name, values):
    ranges = []
    start = previous = None
    for cp in values:
        if start is None:
            start = previous = cp
        elif cp == previous + 1:
            previous = cp
        else:
            ranges.append((start, previous))
            start = previous = cp
    if start is not None:
        ranges.append((start, previous))
    print(f"static const uint32_t {name}[][2] = {{")
    for lo, hi in ranges:
        print(f"    {{0x{lo:X},0x{hi:X}}},")
    print("};")
    print(f"static const int {name}_n = {len(ranges)};")


def main():
    decompositions = []
    lowers = []
    marks = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        char = chr(cp)
        decomp = canonical(cp)
        if decomp != [cp]:
            decompositions.append((cp, decomp))
        lower = cps(char.lower())
        if lower != [cp]:
            lowers.append((cp, lower))
        if unicodedata.category(char) == "Mn":
            marks.append(cp)

    print("/* GENERATED by tools/gen_nomic_unicode.py — do not edit by hand. */")
    print("#ifndef NOMIC_UNICODE_H")
    print("#define NOMIC_UNICODE_H")
    print("#include <stdint.h>")
    print("typedef struct { uint32_t cp, out[4]; uint8_t n; } NomicUnicodeMap;")
    print("static const NomicUnicodeMap nomic_decomp[] = {")
    for cp, values in decompositions:
        padded = values + [0] * (4 - len(values))
        print(f"    {{0x{cp:X},{{0x{padded[0]:X},0x{padded[1]:X},0x{padded[2]:X},0x{padded[3]:X}}},{len(values)}}},")
    print("};")
    print(f"static const int nomic_decomp_n = {len(decompositions)};")
    print("static const NomicUnicodeMap nomic_lower[] = {")
    for cp, values in lowers:
        padded = values + [0] * (4 - len(values))
        print(f"    {{0x{cp:X},{{0x{padded[0]:X},0x{padded[1]:X},0x{padded[2]:X},0x{padded[3]:X}}},{len(values)}}},")
    print("};")
    print(f"static const int nomic_lower_n = {len(lowers)};")
    emit_ranges("nomic_marks", marks)
    print("""static const NomicUnicodeMap *nomic_map_find(
    const NomicUnicodeMap *map, int count, uint32_t cp)
{
    int lo = 0, hi = count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        if (cp < map[mid].cp) hi = mid - 1;
        else if (cp > map[mid].cp) lo = mid + 1;
        else return &map[mid];
    }
    return 0;
}
static inline int nomic_in_ranges(const uint32_t ranges[][2], int count, uint32_t cp)
{
    int lo = 0, hi = count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        if (cp < ranges[mid][0]) hi = mid - 1;
        else if (cp > ranges[mid][1]) lo = mid + 1;
        else return 1;
    }
    return 0;
}
#endif""")


if __name__ == "__main__":
    main()
